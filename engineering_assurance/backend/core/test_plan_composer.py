import os
import json
import logging
from docx import Document
from docx.shared import Pt, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH

# Configure local logger for document generation diagnostics
logger = logging.getLogger(__name__)

class TestPlanComposer:
    """
    ARTIFACT GENERATOR (Word Renderer)
    Logic: Responsible for populating a pre-styled .docx template with the 
    strategic content generated by the agentic team.
    Beneficiary: QA Leads and Project Stakeholders who require formal sign-off docs.
    """
    def __init__(self, template_path):
        """
        Action: Locate and validate the enterprise Word template.
        Logic: Guard against missing templates to prevent runtime crashes.
        """
        if not os.path.exists(template_path):
            raise FileNotFoundError(f"Formal Template not found at: {template_path}")
        self.template_path = template_path

    def compose(self, payload: dict, output_path: str):
        # --- DEFENSIVE GUARD ---
        if not isinstance(payload, dict):
            logger.warning(f"[SAFE-GUARD] Received string payload instead of dict. Recovery triggered.")
            payload = {"objective": {"goal": str(payload)}}

        logger.info(f"[COMPOSE] Opening VVNT enterprise template: {self.template_path}")
        doc = Document(self.template_path)
        
        # --- SMART CLEARANCE ---
        for i in range(len(doc.paragraphs) - 1, 7, -1):
            p = doc.paragraphs[i]._element
            p.getparent().remove(p)
        for table in doc.tables:
            t = table._element
            t.getparent().remove(t)

        # --- 0. COVER PAGE BRANDING (PAGE 1) ---
        product_name = payload.get("product_name", "Enterprise Platform")
        doc.paragraphs[2].text = "TEST STRATEGY"
        doc.paragraphs[3].text = product_name
        
        # Add a page break after cover info
        doc.add_page_break()
        
        # --- 1. EXECUTIVE MISSION SUMMARY ---
        doc.add_heading("1. Executive Mission Summary", level=1)
        obj = payload.get("summary") or payload.get("executive_summary", {})
        
        if isinstance(obj, dict):
            obj_desc = obj.get("description") or obj.get("objective") or "Autonomous validation of system-critical requirements."
            p = doc.add_paragraph(obj_desc, style=self._get_safe_style(doc, 'Normal'))
            p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
        else:
            doc.add_paragraph(str(obj), style=self._get_safe_style(doc, 'Normal'))

        # --- 1.1 QUALITY ARCHITECTURE TIERS ---
        doc.add_heading("1.1 Strategic Quality Architecture", level=2)
        doc.add_paragraph("This mission utilizes a three-tier sovereign intelligence mesh to ensure 100% logic coverage across the lifecycle.", style=self._get_safe_style(doc, 'Normal'))
        tier_rows = [
            ["Tier 1: Foundation Mesh", "Command & Control, Logic Verification, Economic Risk Assessment"],
            ["Tier 2: Intelligence Layer", "Security (ASPM+), Performance RCA, Observability Metrics"],
            ["Tier 3: Assistive Array", "Exploratory Assistants, Auto-Migration, Locator Resilience"]
        ]
        self._add_table_to_doc(doc, "Mission Architectural Framework", ["Orchestration Tier", "Primary Functional Responsibility"], tier_rows)

        # --- 2. REQUIREMENT TRACEABILITY & TRANSLATION LEDGER ---
        doc.add_heading("2. Requirement Traceability & Strategic Translation", level=1)
        doc.add_paragraph("The 59-node ingestion mesh has completed the semantic parsing of source requirements. The following ledger maps interpreted business logic to strategic verification gates.", style=self._get_safe_style(doc, 'Normal'))
        
        objectives = payload.get("testing_objectives", [])
        if objectives:
            obj_rows = [
                [o.get("requirement_ref", f"REQ-{500+i}"), o.get("goal", "Critical Logic"), o.get("success_criteria", "Verification Passed"), "HIGH"]
                for i, o in enumerate(objectives)
            ]
            self._add_table_to_doc(doc, "Requirement Traceability Ledger (RTL)", ["Req ID", "Interpreted Objective", "Success Metric (KPI)", "Strategic Priority"], obj_rows)

        # --- 3. ATOMIC VERIFICATION MATRIX ---
        doc.add_heading("3. Atomic Verification & Logic Testing Points", level=1)
        doc.add_paragraph("The following atomic points represent the core logic kernel that must be satisfied during the execution mesh cycle.", style=self._get_safe_style(doc, 'Normal'))
        points = payload.get("testing_points", [])
