def robust_json_loads(text: str) -> dict:
    try:
        import re
        json_match = re.search(r"\{.*\}", text, re.DOTALL)
        if json_match:
            return json.loads(json_match.group(0))
        return json.loads(text)
    except Exception:
        return {}

def robust_json_list_loads(text: str) -> list:
    try:
        import re
        json_match = re.search(r"\[.*\]", text, re.DOTALL)
        if json_match:
            return json.loads(json_match.group(0))
        return json.loads(text)
    except Exception:
        return []

def engineering_contract_node(state: AgentState):
    """
    AGENT: Engineering Contract
    ROLE: Reads Phase 1 & 2 outputs to produce strict V&V Acceptance Criteria.
    """
    if state.get('error'):
        return state
    task_id = state.get('task_id')
    log_step(task_id, 'Engineering Contract: Generating V&V Acceptance Criteria...', 'Contractor')
    
    # Check if this is a follow-up execution where the contract is already approved
    if state.get('contract_approved'):
        log_step(task_id, 'Engineering Contract: Contract already approved. Proceeding to Forges.', 'Contractor')
        return state

    # Compress combined_data to avoid 15k token bloat
    combined = state.get("combined_data", {})
    compressed_combined = {
        "project": combined.get("project", ""),
        "summary": combined.get("summary", ""),
        "personas": combined.get("personas", []),
        "target_tech_stack": combined.get("target_tech_stack", {}),
        "capabilities": [c.get("name") for c in combined.get("capabilities", [])][:10]  # Just names, not full descriptions
    }

    # Strict isolation: Only pass specific keys, preventing context overflow
    relevant_context = {
        "unified_context_contract": compressed_combined,
        "api_design_spec": state.get("api_design_spec"),
        "db_schema_design": state.get("db_schema_design"),
        "threat_model_advisories": state.get("threat_model_advisories")
    }
    
    # Include Sprint 3 System Specification
    relevant_context["system_specification"] = state.get("system_specification", {})
    
    # Fetch the engineering_tasks generated by the planning_agent_node
    engineering_tasks = state.get("engineering_tasks", [])
    if not engineering_tasks:
        log_step(task_id, 'Engineering Contract: No engineering tasks found in state, falling back.', 'Contractor', level=LogLevel.WARNING)
        engineering_tasks = [{"task_id": "TASK-FALLBACK-001", "title": "Fallback", "description": "Fallback", "capability_refs": ["CAP-FALLBACK-01"]}]

    try:
        # Batch process the engineering tasks to avoid LLM truncation
        batch_size = 3
        final_tasks = []
        total_tasks = len(engineering_tasks)
        
        for batch_idx in range(0, total_tasks, batch_size):
            batch = engineering_tasks[batch_idx:batch_idx + batch_size]
            batch_num = (batch_idx // batch_size) + 1
            total_batches = (total_tasks + batch_size - 1) // batch_size
            
            log_step(task_id, f'Engineering Contract: Enriching batch {batch_num}/{total_batches} ({len(batch)} tasks)...', 'Contractor')
            
            from backend.prompts.tdd.pytest_generator import build_batch_enrichment_prompt
            prompt = build_batch_enrichment_prompt(batch, batch_num, total_batches, relevant_context)
            try:
                content = InferenceCoordinator.execute('Lead V&V Engineering Architect', 'Contract Generation', 'Contractor', prompt, log_step, task_id)
                result = robust_json_loads(content)
                batch_result_tasks = result.get('tasks', [])
                
                # Ensure we didn't lose any tasks
                for original_task in batch:
                    orig_id = original_task.get("id") or original_task.get("task_id")
                    matched = next((t for t in batch_result_tasks if t.get("task_id") == orig_id or t.get("id") == orig_id), None)
                    if matched:
                        # Merge original fields that might have been dropped
                        if "task_id" not in matched:
                            matched["task_id"] = orig_id
                        final_tasks.append(matched)
                    else:
                        logger.warning(f"[CONTRACTOR] LLM skipped task {orig_id} in batch {batch_num}. Generating fallback.")
                        final_tasks.append({
                            "task_id": orig_id,
                            "title": original_task.get("title", "Fallback"),
                            "description": original_task.get("description", "Fallback"),
                            "acceptance_criteria": ["Verify functionality"],
                            "tdd_contract": "def test_fallback():\n    assert True\n",
                            "target_paths": ["packages/backend/core/fallback.py"],
                            "capability_refs": ["CAP-FALLBACK"]
                        })
            except Exception as e:
                logger.error(f"[CONTRACTOR] Batch {batch_num} failed: {e}")
                for original_task in batch:
                    orig_id = original_task.get("id") or original_task.get("task_id")
                    final_tasks.append({
                        "task_id": orig_id,
                        "title": original_task.get("title", "Fallback"),
                        "description": original_task.get("description", "Fallback"),
                        "acceptance_criteria": ["Verify functionality"],
                        "tdd_contract": "def test_fallback():\n    assert True\n",
                        "target_paths": ["packages/backend/core/fallback.py"],
                        "capability_refs": ["CAP-FALLBACK"]
                    })
                    
        tasks = final_tasks
                
        # Add post-processing assertion for capability_refs as requested
        system_spec_caps = relevant_context.get("system_specification", {}).get("capabilities", [])
        known_cap_ids = [c.get("id") for c in system_spec_caps if c.get("id")]
        
        for task in tasks:
            if 'capability_refs' not in task or not task['capability_refs']:
                logger.warning(f"Task {task.get('task_id', 'UNKNOWN')} missing capability_refs. Assigning fallback.")
                task['capability_refs'] = [known_cap_ids[0]] if known_cap_ids else ["CAP-FALLBACK"]
            else:
                valid_refs = []
                for cap_ref in task['capability_refs']:
                    if known_cap_ids and cap_ref not in known_cap_ids:
                        logger.warning(f"Task {task.get('task_id')} references unknown capability {cap_ref}. Ignoring.")
                    else:
                        valid_refs.append(cap_ref)
                
                task['capability_refs'] = valid_refs if valid_refs else ([known_cap_ids[0]] if known_cap_ids else ["CAP-FALLBACK"])
                        
        import hashlib
        tdd_contracts = {}
        for t in tasks:
            # Hash to enforce immutability
            contract_str = t.get('tdd_contract', '')
            sha256_hash = hashlib.sha256(contract_str.encode('utf-8')).hexdigest()
            t['tdd_hash'] = sha256_hash
            tdd_contracts[t['task_id']] = {'code': contract_str, 'contract_hash': None}
            
        # Assemble Handoff Bundle
        from backend.core.bundle_assembler import assemble_handoff_bundle
        bundle_path = assemble_handoff_bundle({
            "mission_id": state.get("mission_id", "local_mission"),
            "system_specification": state.get("system_specification", {}),
            "risk_advisory_report": state.get("risk_advisory_report", {}),
            "tasks": tasks,
            "tdd_contracts": tdd_contracts
        })
        
        log_step(task_id, f'Engineering Contract: Generated {len(tasks)} granular tasks with TDD contracts. Bundle at {bundle_path}', 'Contractor')
        return {
            "tasks": tasks,
            "tdd_contracts": tdd_contracts,
            "handoff_bundle_path": bundle_path
        }
    except Exception as e:
        log_step(task_id, f'Engineering Contract failed ({e}).', 'Contractor', level=LogLevel.ERROR)
        tasks = [{
            "task_id": "TASK-ERR-001",
            "title": "Error Task",
            "description": f"Failed: {str(e)}",
            "acceptance_criteria": ["N/A"],
            "tdd_contract": "def test_error():\n    pass\n",
            "target_paths": ["packages/backend/core/error.py"],
            "tdd_hash": "empty"
        }]
        return {"tasks": tasks, "tdd_contracts": {"TASK-ERR-001": {"code": "def test_error():\n    pass\n", "contract_hash": None}}}

def frontend_forge_node(state: AgentState):
    """
    AGENT: Frontend Forge
    ROLE: Generates React/TS frontend code based on the Engineering Contract.
    """
    if state.get('error'):
        return state
    task_id = state.get('task_id')
    log_step(task_id, 'Frontend Forge: Generating React components...', 'FrontendForge')
    
    # Strict isolation
    relevant_context = {
        "engineering_contract": state.get("engineering_contract"),
        "api_design_spec": state.get("api_design_spec")
    }
    
    prompt = f"""
    ROLE: Senior Frontend Engineer
    TASK: Generate frontend code (React/TypeScript) based on this contract and API spec:
    {json.dumps(relevant_context, default=str)}
    
    RULES:
    1. Your output MUST strictly be a JSON list of file objects.
    2. Each file object MUST have 'path' (string starting exactly with 'apps/frontend/') and 'content' (string code).
    
    OUTPUT: JSON Array of dicts [ {{"path": "apps/frontend/...", "content": "..."}} ]
    """
    
    try:
        content = InferenceCoordinator.execute('Senior Frontend Engineer', 'UI Generation', 'FrontendForge', prompt, log_step, task_id)
        files = robust_json_list_loads(content)
        
        from backend.agents.contracts import ForgeFile
        from pydantic import ValidationError
        validated_files = []
        for file in files:
            path = file.get("path", "")
            if not path.startswith("apps/frontend/"):
                log_step(task_id, f"Forge path violation corrected: {path}", 'FrontendForge', level=LogLevel.WARN)
                path = f"apps/frontend/{path.split('/')[-1]}"
            try:
                validated_file = ForgeFile(path=path, content=file.get("content", ""))
                validated_files.append({"path": validated_file.path, "content": validated_file.content})
                
                # Write to disk to trigger codebase_watcher
                import os
                base_workspace = os.environ.get("WORKSPACE_DIR", os.path.abspath(os.path.join(os.path.dirname(__file__), "../../../")))
                mission_id = state.get("mission_id", "local_mission")
                workspace_dir = os.path.join(base_workspace, "workspace", "missions", str(mission_id), "codebase")
                clean_path = validated_file.path.lstrip("/\\")
                full_path = os.path.join(workspace_dir, clean_path)
                os.makedirs(os.path.dirname(full_path), exist_ok=True)
                with open(full_path, "w", encoding="utf-8") as f:
                    f.write(validated_file.content)
            except ValidationError as ve:
                for err in ve.errors():
                    field = '.'.join(str(loc) for loc in err.get('loc', ['unknown']))
                    msg = err.get('msg', 'validation failed')
                    log_step(task_id, f'[FORGE-VIOLATION] Frontend file "{path}" field "{field}": {msg}', 'FrontendForge', level=LogLevel.ERROR)
                logger.error("[FORGE] FrontendForge ForgeFile validation failed for path=%s: %s", path, ve)
            
        log_step(task_id, f'Frontend Forge: Generated {len(validated_files)} files.', 'FrontendForge')
        return {"frontend_forge_code": validated_files}
    except Exception as e:
        log_step(task_id, f'Frontend Forge failed ({e}).', 'FrontendForge', level=LogLevel.ERROR)
        return {"forge_errors": [str(e)]}

